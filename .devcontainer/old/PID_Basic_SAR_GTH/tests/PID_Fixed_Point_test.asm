; ============================================================
; PID_Basic_SAR Q8.8 fixed-point arithmetic test
;
; Q8.8 scale = 256
; Kp = 25.0 = 25 * 256 = 6400
;
; Test 1: 25 * -0.5 = -12.5
; Test 2: 25 *  0.5 =  12.5
; Test 3: 25 *  3.0 =  75.0
; Test 4: -25.0 * -0.5 = 12.5
; ============================================================

; Kp = 25.0 in Q8.8
LI    r1, #6400


; ------------------------------------------------------------
; Test 1: negative number
;
; error = -0.5
; Q8.8 error = -0.5 * 256 = -128
;
; raw multiplication:
; 6400 * -128 = -819200
;
; scale back down:
; -819200 >>> 8 = -3200
; -3200 / 256 = -12.5
; ------------------------------------------------------------

LI    r11, #128
SUB   r2, r0, r11       ; r2 = -128 = -0.5

MUL   r3, r1, r2        ; r3 = -819200, Q16.16
SAR   r4, r3, #8        ; r4 = -3200 = -12.5 in Q8.8

STORE r4, [0x0100]
LOAD  r13, [0x0100]     ; memory read-back


; ------------------------------------------------------------
; Test 2: positive number
;
; error = 0.5
; Q8.8 error = 128
;
; 6400 * 128 = 819200
; 819200 >>> 8 = 3200
; 3200 / 256 = 12.5
; ------------------------------------------------------------

LI    r5, #128           ; r5 = 0.5

MUL   r6, r1, r5        ; r6 = 819200, Q16.16
SAR   r7, r6, #8        ; r7 = 3200 = 12.5 in Q8.8

STORE r7, [0x0104]
LOAD  r14, [0x0104]     ; memory read-back


; ------------------------------------------------------------
; Test 3: whole number
;
; error = 3.0
; Q8.8 error = 3 * 256 = 768
;
; 6400 * 768 = 4915200
; 4915200 >>> 8 = 19200
; 19200 / 256 = 75.0
; ------------------------------------------------------------

LI    r8, #768           ; r8 = 3.0

MUL   r9, r1, r8        ; r9 = 4915200, Q16.16
SAR   r10, r9, #8       ; r10 = 19200 = 75.0 in Q8.8

STORE r10, [0x0108]
LOAD  r15, [0x0108]     ; memory read-back


; ------------------------------------------------------------
; Test 4: negative multiplied by negative
;
; -25.0 * -0.5 = 12.5
;
; -25.0 in Q8.8 = -6400
; -0.5  in Q8.8 = -128
;
; Raw product:
; -6400 * -128 = 819200
;
; Scaled result:
; 819200 >>> 8 = 3200
; 3200 / 256 = 12.5
; ------------------------------------------------------------

LI    r18, #6400
SUB   r18, r0, r18       ; r18 = -6400 = -25.0

LI    r19, #128
SUB   r19, r0, r19       ; r19 = -128 = -0.5

MUL   r20, r18, r19      ; r20 = 819200
SAR   r21, r20, #8       ; r21 = 3200 = 12.5

; ADD check: -12.5 + 12.5 = 0
ADD   r17, r4, r7

; JMP check: this instruction must be skipped
JMP   jump_worked
LI    r16, #1           ; must not execute

jump_worked:
HALT
